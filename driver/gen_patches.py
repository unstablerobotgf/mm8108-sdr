# Emit src/patches.h from tools/owner.diff() (stock vs ringfree word diff) and radio.py's clamp/div2 sites.
# The header carries only our side of each patch (mask/bits, NOP sites) plus one FNV-1a signature of the stock
# words, which the driver recomputes from the user's firmware ELF at boot. No vendor code ends up in the repo.
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, '..', 'tools'))
import owner, radio

ASSERT_SITE, ASSERT_BCAST = 0x50e502, 0x501f20      # UPHY ring-take ASSERT entry (uphy_meas_capture_fft_loop); uphy_assert_fail's jal ring_all_doorbells
# Containing functions from the Binja PHY DB (rom/mm8108_phy.elf.bndb, 2026-10-29): start -> name. Comments only.
FUNCS = {0x506144: 'uphy_boot_init', 0x507dbc: 'uphy_rx_sync_handler', 0x5085c8: 'uphy_rxcap_disable',
         0x50adec: 'uphy_rxfe_config_bw', 0x50c684: 'uphy_rxcap_set_ring', 0x50c6b0: 'uphy_rxcap_set_ring_checked',
         0x5455cc: 'lphy_rxcap_stop', 0x5455f8: 'lphy_rxcap_start'}
# Per-word detail where the patch group alone does not say what the instruction does
NAMES = {0x507e18: 'uphy_rxcap_on_detect call (snap)', 0x507e1c: 'uphy_rxcap_on_detect call (snap)',
         0x50c6d0: 'ptr==base check (safety)', 0x545618: 'ptr==base check (safety)'}

def func(addr):
    s = max((s for s in FUNCS if s <= addr), default=None)
    return f'{FUNCS[s]}+0x{addr - s:x}' if s is not None else f'0x{addr:06x}'

def fnv64(words):
    h = 0xcbf29ce484222325
    for w in words:
        for b in w: h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h

def label(addr, old, new):
    g = [k for k in ('snap', 'bit0', 'baselen') if (addr, old, new) in owner.words_for([k])]
    return f'{func(addr)}: {NAMES.get(addr, ("/".join(g) or "ring") + " write")}'

sig_words, L = [], [
    '// Generated by gen_patches.py; do not edit. Stock words are read from the firmware ELF at boot and checked',
    '// against STOCK_SIG, so nothing of the vendor image lives here. Patched word = (stock & ~mask) | bits.',
    '#pragma once', '#include <stdint.h>',
    'struct MMPatch { uint32_t addr, mask, bits; bool safety; };',
    '// ring-free words; safety words (setter2 ptr==base checks) are skipped in full-rate mode so the fw ASSERT parks UPHY',
    'static const MMPatch RING_PATCHES[] = {']
for addr, old, new in sorted(owner.diff()):
    mask = (0xffff if old[0:2] != new[0:2] else 0) | (0xffff0000 if old[2:4] != new[2:4] else 0)
    ow, nw = int.from_bytes(old, 'little'), int.from_bytes(new, 'little')
    assert (ow & ~mask & 0xffffffff) | (nw & mask) == nw, hex(addr)
    L.append(f'    {{0x{addr:06x}, 0x{mask:08x}, 0x{nw & mask:08x}, {"true" if addr in owner.SAFETY_WORDS else "false"}}},   // {label(addr, old, new)}')
    sig_words.append(old)
L += ['};',
      'struct MMSite { uint32_t win; int off; };   // 4 B instruction to NOP at off inside an 8 B RMW window',
      f'static const MMSite CLAMP_SITE = {{0x{radio.CLAMP_W:06x}, 2}};   // MAC SET_CHANNEL 750-950 MHz clamp (bltu), MAC sub_2868c8+0xc0',
      'static const MMSite DIV2_SITES[] = {' + ', '.join(f'{{0x{wa:06x}, {off}}}' for wa, off, _ in radio.DIV2_SITES) + '};   // branches at uphy_set_lo+0x3e / lphy_set_lo+0x54, "f > 1 GHz: no doubling"',
      f'static const uint32_t ASSERT_SITE = 0x{ASSERT_SITE:06x}, ASSERT_BCAST = 0x{ASSERT_BCAST:06x};   // UPHY ring-take ASSERT entry; uphy_assert_fail jal ring_all_doorbells']
sig_words.append(owner.stock_bytes(radio.CLAMP_W + 2, 4))
for wa, off, _ in radio.DIV2_SITES: sig_words.append(owner.stock_bytes(wa + off, 4))
sig_words += [owner.stock_bytes(ASSERT_SITE, 4), owner.stock_bytes(ASSERT_BCAST, 4)]
L += ['// FNV-1a 64 over the stock words of RING_PATCHES, CLAMP_SITE, DIV2_SITES, ASSERT_SITE, ASSERT_BCAST, in that order',
      f'static const uint64_t STOCK_SIG = 0x{fnv64(sig_words):016x}ull;']

if __name__ == '__main__':
    open(os.path.join(HERE, 'src', 'patches.h'), 'w').write('\n'.join(L) + '\n')
    print(f'{len(owner.diff())} ring words, {len(sig_words)} stock words signed')
